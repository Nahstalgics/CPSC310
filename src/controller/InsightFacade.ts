	private readonly cfg: GrammarConfig = InsightFacade.makeDefaultConfig(); // one config per instance

	private static makeDefaultConfig(): GrammarConfig {
		// idstring: one or more chars except underscore
		const IDSTRING = "[^_]+";
		// mkey = "<idstring>_<mfield>"
		const MFIELD = "(avg|pass|fail|audit|year)";
		// skey = "<idstring>_<sfield>"
		const SFIELD = "(dept|id|instructor|title|uuid)";

		return {
			LOGICS: new Set(["AND", "OR"]),
			NEGATION: "NOT",
			NUM_CMPS: new Set(["LT", "GT", "EQ"]), // MCOMPARATOR
			STR_CMPS: new Set(["IS"]), // SCOMPARATOR

			// matches a QUOTED property name (as text)
			// RegExp() describes a text pattern you can use to test, search, or extract strings
			MKEY_RE: new RegExp(`^"${IDSTRING}_${MFIELD}"$`),
			SKEY_RE: new RegExp(`^"${IDSTRING}_${SFIELD}"$`),

			// Unquoted variants (objects parsed by JS have unquoted property names)
			MKEY_UNQUOTED_RE: new RegExp(`^${IDSTRING}_${MFIELD}$`),
			SKEY_UNQUOTED_RE: new RegExp(`^${IDSTRING}_${SFIELD}$`),
		};
	}

	// copied Colins addDataset (git version: f35829c)
	private idValid(id: string): boolean {
		return !(id.includes("_") || id.trim().length === 0);
	}

	private parseSection(section: any): Section {
		//generated by chatgpt
		const requiredFields = [
			"Avg",
			"Pass",
			"Fail",
			"Audit",
			"Course",
			"Title",
			"Professor",
			"Subject",
			"Year",
			"Section",
			"id",
		];

		for (const field of requiredFields) {
			if (section[field] === undefined || section[field] === null) {
				throw new InsightError(`Missing required field: ${field}`);
			}
		}
		//end of genai
		const specialYear: number = 1900;
		return {
			uuid: String(section.id),
			id: section.Course,
			title: section.Title,
			instructor: section.Professor,
			dept: section.Subject,
			year: section.Section === "overall" ? specialYear : Number(section.Year),
			avg: Number(section.Avg),
			pass: Number(section.Pass),
			fail: Number(section.Fail),
			audit: Number(section.Audit),
		};
	}

	private parseInsightDatasetExtend(idString: string, rows: number, sectionArray: Section[]): InsightDatasetExtend {
		return {
			id: idString,
			kind: InsightDatasetKind.Sections,
			numRows: rows,
			sections: sectionArray,
		};
	}

