	public async addDataset(id: string, content: string, kind: InsightDatasetKind): Promise<string[]> {
		let allDatasets: InsightDatasetExtend[];
		try {
			allDatasets = await this.readFromFile();
		} catch {
			throw new InsightError("Unable to read JSON");
		}
		if (allDatasets.some((data: InsightDatasetExtend): boolean => data.id === id)) {
			throw new InsightError("Already added id");
		}
		if (kind === InsightDatasetKind.Sections && this.idValid(id)) {
			let dataset: Section[];
			try {
				dataset = await this.parseSections(content);
			} catch {
				throw new InsightError("");
			}
			if (dataset.length === 0) {
				throw new InsightError("Dataset contained no valid sections");
			}
			allDatasets.push(this.parseInsightDatasetExtend(id, dataset.length, dataset));
			try {
				await fs.outputJSON("./data/allDatasets.json", allDatasets);
			} catch {
				throw new InsightError();
			}
			return allDatasets.map((data: InsightDatasetExtend) => data.id);
		} else {
			throw new InsightError("Invalid InsightDatasetKind or/and id");
		}
	}

